def upgrade_app_js(portal):
    titles_path = os.path.join(WORKSPACE_DIR, portal, '03_qa', 'config', 'screen-titles.json')
    target_app_js = os.path.join(WORKSPACE_DIR, portal, '.report', 'viewer', 'app.js')
    
    if not os.path.exists(titles_path):
        print(f"[-] Missing titles: {titles_path}")
        return

    with open(titles_path, 'r', encoding='utf-8-sig') as f:
        titles_data = json.load(f)

    with open(DC_APP_JS, 'r', encoding='utf-8-sig') as f:
        dc_code = f.read()

    # 1. Replace KNOWN_SCREEN_TITLES
    titles_js = json.dumps(titles_data, indent=2, ensure_ascii=False)
    # Match var KNOWN_SCREEN_TITLES = { ... };
    dc_code = re.sub(
        r'var KNOWN_SCREEN_TITLES\s*=\s*\{[\s\S]*?\};',
        f'var KNOWN_SCREEN_TITLES = {titles_js};',
        dc_code,
        count=1
    )

    # 2. Replace MENU_GROUPS
    groups = MENU_GROUPS_CONFIG.get(portal, [])
    groups_js = json.dumps(groups, indent=2, ensure_ascii=False)
    dc_code = re.sub(
        r'var MENU_GROUPS\s*=\s*\[[\s\S]*?\];',
        f'var MENU_GROUPS = {groups_js};',
        dc_code,
        count=1
    )

    # Write target with UTF-8 BOM
    with open(target_app_js, 'w', encoding='utf-8-sig', newline='\n') as f:
        f.write(dc_code)
    print(f"[+] Successfully upgraded viewer app.js for {portal}")

if __name__ == '__main__':
    for p in ['cci-store-location-web', 'cci-scm-web', 'cci-income-web']:
        upgrade_app_js(p)
